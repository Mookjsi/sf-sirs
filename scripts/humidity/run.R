# Run an explicitly selected script inside the isolated humidity extension.
args <- commandArgs(trailingOnly = TRUE)
if (length(args)!=1L) stop('Usage: Rscript scripts/humidity/run.R "code/path/to/script.R"')
launcher <- sub('^--file=', '', grep('^--file=', commandArgs(FALSE), value=TRUE)[1])
repo <- normalizePath(file.path(dirname(launcher), '../..'), mustWork=TRUE)
root <- normalizePath(file.path(repo, 'extensions/humidity'), mustWork=TRUE)
if (grepl('^(/|[A-Za-z]:)', args[1]) || any(strsplit(args[1], '/', fixed=TRUE)[[1]] == '..')) stop('Script path must stay inside the extension')
entry <- normalizePath(file.path(root, args[1]), mustWork=TRUE)
if (!startsWith(entry, paste0(root, '/code/')) || !grepl('\\.R$', entry)) stop('Select an existing R script under code/')
if (!file.exists(file.path(root, 'ARCHIVE_MANIFEST.csv'))) stop('Humidity provenance manifest is missing')
safe <- c('code/analysis/2013-2017 training/plot_forecast_metrics.R',
          'code/analysis/2013-2017 training/to define weak shift using humidity 2013-2017.R')
if (!(args[1] %in% safe)) stop('UNVERIFIED: entry may fit or overwrite saved results; no safe launcher path is defined')
output <- file.path(root,'outputs',tools::file_path_sans_ext(basename(entry)))
dir.create(output,recursive=TRUE,showWarnings=FALSE)
options(forecast.metrics.output_dir=output, humidity.peak_shift.output_dir=output)
Sys.setenv(HUMIDITY_OUTPUT_DIR=output)
setwd(root)
source('code/run_handoff.R', local=TRUE)
